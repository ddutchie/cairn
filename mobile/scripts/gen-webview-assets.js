/**
 * Generates self-contained WebView asset modules for offline KaTeX + Mermaid.
 *
 * The mobile app is offline-first (no CDN), and loading fonts/scripts over
 * file:// inside a WebView is brittle. So we bundle the library sources directly
 * as JS string modules committed to the repo:
 *
 *   src/webview-assets/katex-assets.ts   — KaTeX JS + CSS (woff2 fonts inlined
 *                                           as base64 data: URLs, woff/ttf refs
 *                                           stripped)
 *   src/webview-assets/mermaid-assets.ts — Mermaid JS
 *
 * Re-run after bumping katex/mermaid:  node scripts/gen-webview-assets.js
 */
const fs = require("fs");
const path = require("path");

const MOBILE = path.resolve(__dirname, "..");
const OUT_DIR = path.join(MOBILE, "src", "webview-assets");
const KATEX = path.join(MOBILE, "node_modules", "katex", "dist");
const MERMAID = path.join(MOBILE, "node_modules", "mermaid", "dist");

fs.mkdirSync(OUT_DIR, { recursive: true });

// ── KaTeX ──────────────────────────────────────────────────────────────────
const katexJs = fs.readFileSync(path.join(KATEX, "katex.min.js"), "utf8");
let katexCss = fs.readFileSync(path.join(KATEX, "katex.min.css"), "utf8");

// Inline every woff2 font as a data: URL, and drop the woff/ttf src entries so
// the WebView never issues a file:// request.
katexCss = katexCss.replace(/@font-face\{([^}]*)\}/g, (block) => {
  // Extract the woff2 filename.
  const m = /url\(fonts\/([^)]+?\.woff2)\)/.exec(block);
  if (!m) return block;
  const fontFile = m[1];
  const fontPath = path.join(KATEX, "fonts", fontFile);
  if (!fs.existsSync(fontPath)) return block;
  const b64 = fs.readFileSync(fontPath).toString("base64");
  const dataUrl = `url(data:font/woff2;base64,${b64}) format("woff2")`;
  // Replace the whole `src:` declaration (runs to the closing brace) with just
  // the inlined woff2 — drops the woff/ttf fallbacks so no file:// requests.
  return block.replace(/src:[^}]+/, `src:${dataUrl}`);
});

writeModule("katex-assets.ts", {
  KATEX_JS: katexJs,
  KATEX_CSS: katexCss,
});

// ── Mermaid ─────────────────────────────────────────────────────────────────
const mermaidJs = fs.readFileSync(path.join(MERMAID, "mermaid.min.js"), "utf8");
writeModule("mermaid-assets.ts", { MERMAID_JS: mermaidJs });

// ── D3 ──────────────────────────────────────────────────────────────────────
// D3 powers the offline Knowledge Graph WebView (force-directed layout). It may
// be hoisted to the repo root node_modules, so resolve from either location.
const D3_CANDIDATES = [
  path.join(MOBILE, "node_modules", "d3", "dist", "d3.min.js"),
  path.join(MOBILE, "..", "node_modules", "d3", "dist", "d3.min.js"),
];
const d3Path = D3_CANDIDATES.find((p) => fs.existsSync(p));
if (!d3Path) throw new Error("d3.min.js not found in mobile or root node_modules");
const d3Js = fs.readFileSync(d3Path, "utf8");
writeModule("d3-assets.ts", { D3_JS: d3Js });

console.log("[gen-webview-assets] wrote katex-assets.ts + mermaid-assets.ts + d3-assets.ts");

/** Emit a TS module that exports each entry as a backtick string constant. */
function writeModule(filename, entries) {
  const header =
    "// AUTO-GENERATED by scripts/gen-webview-assets.js — do not edit by hand.\n" +
    "// Bundled library source for offline WebView rendering. Re-run the script\n" +
    "// after upgrading katex/mermaid.\n/* eslint-disable */\n\n";
  const body = Object.entries(entries)
    .map(([name, value]) => {
      // Escape backslashes, backticks and ${ so the value is a safe template
      // literal.
      const escaped = value
        .replace(/\\/g, "\\\\")
        .replace(/`/g, "\\`")
        .replace(/\$\{/g, "\\${");
      return `export const ${name} = \`${escaped}\`;\n`;
    })
    .join("\n");
  fs.writeFileSync(path.join(OUT_DIR, filename), header + body);
}
